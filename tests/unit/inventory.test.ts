import { expect, it } from 'vitest';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { LEVELS } from '../../src/content/levels';
import { MEDIA } from '../../src/content/media';
import { SOURCES } from '../../src/content/sources';
import { mockPapers } from '../../src/features/exam/papers';
import type { LevelId, PracticeSet } from '../../src/content/types';

// Keeps the inventory table in docs/content-and-sources.md true to the app's real data.
// If this fails after a content change, regenerate the table with:  UPDATE_DOCS=1 npx vitest run tests/unit/inventory.test.ts

const DOC = 'docs/content-and-sources.md';
const START = '<!-- inventory:start (generated by tests/unit/inventory.test.ts; do not edit by hand) -->';
const END = '<!-- inventory:end -->';

const hsk = JSON.parse(readFileSync('public/packs/core/hsk.json', 'utf8'));
const dict = JSON.parse(readFileSync('public/packs/core/dict.json', 'utf8'));

function parts(sets: PracticeSet[]): string {
  const counts = new Map<string, number>();
  for (const s of sets) for (const g of s.groups) counts.set(g.officialPart, (counts.get(g.officialPart) ?? 0) + s.questions.filter((q) => q.groupId === g.id).length);
  return [...counts].map(([p, n]) => `${p} ${n}`).join(', ');
}

function inventory(): string {
  const rows: string[] = ['| What | HSK 1 | HSK 2 |', '| --- | --- | --- |'];
  const both = (label: string, f: (l: LevelId) => string | number) => rows.push(`| ${label} | ${f(1)} | ${f(2)} |`);
  both('Practice sets', (l) => `${LEVELS[l].sets.length} (${LEVELS[l].sets.map((s) => s.title.replace('Practice set ', '')).join(', ')})`);
  both('Questions in practice sets', (l) => `${LEVELS[l].sets.reduce((n, s) => n + s.questions.length, 0)} (${parts(LEVELS[l].sets)})`);
  both('Picture sets (Reading Part 1)', (l) =>
    LEVELS[l].pictureSets.length ? `${LEVELS[l].pictureSets.length}: ${LEVELS[l].pictureSets.reduce((n, s) => n + s.questions.length, 0)} questions, ${LEVELS[l].pictureSets.reduce((n, s) => n + (s.groups[0].options?.length ?? 0), 0)} photos` : 'none yet',
  );
  both('Mock exams', (l) => `${mockPapers(l).length} (${mockPapers(l)[0]?.questions.length ?? 0} questions each)`);
  both('Listening', () => 'not built yet');
  both('Syllabus reading characters new at this level', (l) => hsk.readingChars[l].length);
  rows.push(`| Writing characters (official 书写字 list, shared by HSK 1–2) | ${hsk.writingChars['1-2'].length} | ${hsk.writingChars['1-2'].length} |`);
  const words = (l: number) => new Set(dict.entries.filter((e: [string, string, string, string[], number]) => e[4] === l).map((e: string[]) => e[0])).size;
  both('Syllabus words new at this level (found in CC-CEDICT)', (l) => words(l));

  const other = [
    '',
    '| Shared data | Amount |',
    '| --- | --- |',
    `| Dictionary entries (CC-CEDICT ${dict.meta.version.slice(0, 10)}) | ${dict.entries.length} |`,
    `| Stroke-order files | ${readdirSync('public/packs/strokes').filter((f) => f.endsWith('.json')).length} |`,
    `| Photos (all ${[...new Set(Object.values(MEDIA).map((m) => m.licence))].join(', ')}) | ${Object.keys(MEDIA).length} |`,
    `| Recordings | 0 |`,
    `| Outside sources listed on the Sources & Licences screen | ${SOURCES.length} |`,
  ];
  return [START, ...rows, ...other, END].join('\n');
}

it('the inventory in docs/content-and-sources.md matches the app', () => {
  const doc = readFileSync(DOC, 'utf8');
  const block = doc.slice(doc.indexOf(START), doc.indexOf(END) + END.length);
  const fresh = inventory();
  if (process.env.UPDATE_DOCS) writeFileSync(DOC, doc.replace(block, fresh));
  else expect(block).toBe(fresh);
});
